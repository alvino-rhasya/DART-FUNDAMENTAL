/**
 * Abstract Class adalah sebuah Class yang tidak dapat dibuat menjadi objek (instance)
 * TETAPI dapat digunakan sebagai class untuk ParentClass (superclass)
 * untuk diwariskan kepada class lain.
 * 
 * dengan kata lain:
 * 1. dapat diwarisi (inheritance)
 * 2. dapat memiliki properties
 * 3. dapat memiliki methods
 * 4. tidak dapat dijadikan sebagai objek
 * 
 * AbstractClass dijadikan sebagai kerangka dasar
 * yang akan digunakan oleh kelas turunannya
 * 
 * ada kata kunci
 * abstract class NamaClass{}
 */